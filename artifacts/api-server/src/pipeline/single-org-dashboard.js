const path = require("path");

// ─────────────────────────────── text helpers ───────────────────────────────
const ENT = { amp: "&", lt: "<", gt: ">", quot: '"', apos: "'", nbsp: " ", middot: "·", rarr: "→", mdash: "—", ndash: "–", times: "×", hellip: "…", rsquo: "’", lsquo: "‘", ldquo: "“", rdquo: "”" };
function decode(s) {
  return String(s)
    .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)))
    .replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(parseInt(d, 10)))
    .replace(/&([a-z]+);/gi, (m, n) => (ENT[n.toLowerCase()] !== undefined ? ENT[n.toLowerCase()] : m));
}
function text(html) {
  return decode(String(html).replace(/<[^>]+>/g, " ")).replace(/\s+/g, " ").trim();
}
function esc(s) {
  return String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}
function sectionOf(html, id) {
  const i = html.indexOf(`id="${id}"`);
  if (i < 0) return "";
  const j = html.indexOf("</section>", i);
  return html.slice(i, j < 0 ? html.length : j);
}
function parseNum(t) {
  t = String(t).trim();
  let m = t.match(/^([\d.]+)\s*K$/i);
  if (m) return parseFloat(m[1]) * 1000;
  m = t.match(/^([\d.]+)\s*M$/i);
  if (m) return parseFloat(m[1]) * 1e6;
  m = t.match(/^([\d.]+)\s*%?$/);
  return m ? parseFloat(m[1]) : null;
}
const NOHANDLE = "–"; // en dash: no handle configured
const FAILED = "✕";
function cellVal(t) {
  t = text(t);
  if (t === NOHANDLE) return { v: null, marker: "nohandle", raw: t };
  if (t === FAILED) return { v: null, marker: "failed", raw: t };
  if (t === "~") return { v: null, marker: "unreliable", raw: t };
  if (t === "—" || t === "") return { v: null, marker: "none", raw: t };
  return { v: parseNum(t), marker: null, raw: t };
}
function parseTable(tableHtml) {
  const thead = (tableHtml.match(/<thead[^>]*>([\s\S]*?)<\/thead>/) || [])[1] || "";
  const body = tableHtml.replace(/<thead[^>]*>[\s\S]*?<\/thead>/, "");
  const headRows = [...thead.matchAll(/<tr[^>]*>([\s\S]*?)<\/tr>/g)].map((m) => m[1]);
  const headers = headRows.length ? [...headRows[0].matchAll(/<th[^>]*>([\s\S]*?)<\/th>/g)].map((m) => text(m[1])) : [];
  const cells = (r) => [...r.matchAll(/<td([^>]*)>([\s\S]*?)<\/td>/g)].map((c) => ({ attrs: c[1], html: c[2], text: text(c[2]) }));
  const extraHead = headRows.slice(1).map(cells);
  const rows = [...body.matchAll(/<tr[^>]*>([\s\S]*?)<\/tr>/g)].map((m) => cells(m[1]));
  return { headers, extraHead, rows };
}
function tablesOf(sectionHtml) {
  return [...sectionHtml.matchAll(/<table[^>]*>[\s\S]*?<\/table>/g)].map((m) => parseTable(m[0]));
}
const hIdx = (headers, re) => headers.findIndex((h) => re.test(h));

// ─────────────────────────────── base-report parser ─────────────────────────
const PRINT_OUTLETS_RE = /times of india|hindustan times|the hindu|indian express|deccan herald/i;

function parseBaseReport(html) {
  const plain = text(html);
  const period = plain.match(/Period:\s*(\d{4}-\d{2}-\d{2})\s*(?:→|->)\s*(\d{4}-\d{2}-\d{2})/);
  if (!period) throw new Error("Base report: could not find the 'Period: from → to' line");
  const gen = plain.match(/Generated by ([^·]+)·\s*([^·]+?)\s*·\s*([A-Za-z]{3}, \d{1,2} [A-Za-z]{3} \d{4})/);
  const generatedDate = gen ? new Date(gen[3] + " UTC").toISOString().slice(0, 10) : null;
  const meta = {
    from: period[1],
    to: period[2],
    days: Math.round((Date.parse(period[2]) - Date.parse(period[1])) / 86400000) + 1,
    platform: gen ? gen[2].trim() : "AQ Intelligence",
    generated: generatedDate,
  };

  // ── press (print/online) ──
  const sov = sectionOf(html, "sov");
  const pt = tablesOf(sov)[0];
  if (!pt) throw new Error("Base report: press table not found (section id=sov)");
  const oi = hIdx(pt.headers, /^org/i);
  const ti = hIdx(pt.headers, /^total$/i);
  const printOutlets = pt.headers.filter((h, i) => i !== oi && i !== ti);
  const orgs = [];
  const press = {}; // org -> {total, byOutlet:{}}
  for (const r of pt.rows) {
    if (r.length < 3) continue;
    const org = r[oi].text;
    if (!org) continue;
    orgs.push(org);
    const byOutlet = {};
    pt.headers.forEach((h, i) => {
      if (i === oi || i === ti) return;
      byOutlet[h] = parseInt(r[i].text, 10) || 0;
    });
    const total = ti >= 0 ? parseInt(r[ti].text, 10) || 0 : Object.values(byOutlet).reduce((a, b) => a + b, 0);
    press[org] = { total, byOutlet };
  }
  const cov = text(sov).match(/All AQ coverage\s*—\s*(\d+)\s*articles?\s*·\s*(\d+)\s*org mentions/i);
  meta.distinctArticles = cov ? parseInt(cov[1], 10) : null;
  meta.orgMentions = cov ? parseInt(cov[2], 10) : null;

  // ── TV ──
  const tv = {};
  const tvChannels = [];
  for (const t of tablesOf(sectionOf(html, "tv"))) {
    const o = hIdx(t.headers, /^org/i);
    const tt = hIdx(t.headers, /^total$/i);
    if (o < 0) continue;
    t.headers.forEach((h, i) => { if (i !== o && i !== tt && !tvChannels.includes(h)) tvChannels.push(h); });
    for (const r of t.rows) {
      if (r.length < 3) continue;
      const org = r[o].text;
      tv[org] = tv[org] || { total: 0, byChannel: {} };
      t.headers.forEach((h, i) => {
        if (i === o || i === tt) return;
        const n = parseInt(r[i].text, 10) || 0;
        tv[org].byChannel[h] = n;
        tv[org].total += n;
      });
    }
  }

  // ── momentum ──
  const mt = tablesOf(sectionOf(html, "momentum"))[0];
  const weeks = [];
  const momentum = {};
  let fieldWeekly = null;
  if (mt) {
    const o = hIdx(mt.headers, /^org/i);
    const tt = hIdx(mt.headers, /^total$/i);
    mt.headers.forEach((h, i) => { if (i !== o && i !== tt) weeks.push({ label: h, idx: i }); });
    for (const r of mt.rows) {
      if (r.length < 3) continue;
      const name = r[o].text;
      const vals = weeks.map((w) => parseInt(r[w.idx].text, 10) || 0);
      const total = tt >= 0 ? parseInt(r[tt].text, 10) || 0 : vals.reduce((a, b) => a + b, 0);
      if (/^(all orgs|press \(all orgs\))/i.test(name)) fieldWeekly = { vals, total };
      else momentum[name] = { vals, total };
    }
  }

  // ── topic ownership ──
  const tt0 = tablesOf(sectionOf(html, "topics"))[0];
  const topics = [];
  const topicCounts = {};
  if (tt0) {
    const o = hIdx(tt0.headers, /^org/i);
    const tot = hIdx(tt0.headers, /^total$/i);
    tt0.headers.forEach((h, i) => { if (i !== o && i !== tot) topics.push({ name: h, idx: i }); });
    for (const r of tt0.rows) {
      if (r.length < 3) continue;
      const org = r[o].text;
      topicCounts[org] = {};
      for (const tp of topics) {
        const m = r[tp.idx].text.match(/(?:Active|Leader|Not Present)\s*·\s*(\d+)/i);
        topicCounts[org][tp.name] = m ? parseInt(m[1], 10) : 0;
      }
    }
  }

  // ── citations (per-org article lists) ──
  const citations = {};
  const appendix = sectionOf(html, "appendix");
  for (const b of appendix.split(/<details\s/).slice(1)) {
    const m = b.match(/font-weight:600;color:var\(--text\)">([\s\S]*?)<span/);
    if (!m) continue;
    const org = text(m[1]);
    citations[org] = [];
    for (const r of b.matchAll(/<tr><td>\d+<\/td>([\s\S]*?)<\/tr>/g)) {
      const td = [...r[1].matchAll(/<td[^>]*>([\s\S]*?)<\/td>/g)].map((x) => x[1]);
      if (td.length < 6) continue;
      const headline = text(td[2].replace(/<span[^>]*title="Org appears[^>]*>[\s\S]*?<\/span>/, "")).replace(/\s*✓ cit\s*$/, "");
      const um = td[5].match(/href="([^"]+)"/);
      citations[org].push({
        outlet: text(td[0]),
        date: text(td[1]),
        headline,
        classification: text(td[3]),
        keywords: [...td[4].matchAll(/<span[^>]*>([\s\S]*?)<\/span>/g)].map((k) => text(k[1])),
        url: um ? decode(um[1]) : null,
      });
    }
  }

  // ── LLM / AEO ──
  const aeo = sectionOf(html, "aeo");
  const at = tablesOf(aeo);
  const llm = {};
  let assistants = [];
  const rankT = at.find((t) => hIdx(t.headers, /^rank$/i) >= 0 && hIdx(t.headers, /^total$/i) >= 0);
  if (rankT) {
    const o = hIdx(rankT.headers, /^org/i);
    const tot = hIdx(rankT.headers, /^total$/i);
    assistants = rankT.headers.filter((h, i) => i > tot);
    for (const r of rankT.rows) {
      if (r.length < 4) continue;
      const org = r[o].text;
      const per = {};
      assistants.forEach((a, k) => {
        const m = r[tot + 1 + k].text.match(/(\d+)\s*\/\s*(\d+)/);
        per[a] = m ? parseInt(m[1], 10) : 0;
      });
      llm[org] = { total: parseInt(r[tot].text, 10) || 0, per };
    }
  }
  const qT = at.find((t) => hIdx(t.headers, /^q#/i) >= 0);
  const questions = [];
  const questionCells = {}; // org -> [{named,of}]
  if (qT) {
    const orgCols = qT.headers.map((h, i) => ({ h, i })).filter((x) => x.i >= 2);
    for (const r of qT.rows) {
      if (r.length < 3 || !/^Q\d+$/i.test(r[0].text)) continue;
      const qHtml = r[1].html.split(/<details/i)[0];
      questions.push({ n: r[0].text, text: text(qHtml) });
      for (const c of orgCols) {
        const m = (r[c.i] ? r[c.i].text : "").match(/(\d+)\s*\/\s*(\d+)/);
        (questionCells[c.h] = questionCells[c.h] || []).push(m ? { named: parseInt(m[1], 10), of: parseInt(m[2], 10) } : { named: 0, of: assistants.length || 3 });
      }
    }
  }
  const nAns = questions.length * (assistants.length || 3);

  // ── social ──
  const social = {};
  const soc = sectionOf(html, "social");
  const st = tablesOf(soc).find((t) => hIdx(t.headers, /^li posts$/i) >= 0);
  if (!st) throw new Error("Base report: social table not found");
  const col = (re) => hIdx(st.headers, re);
  const C = {
    org: col(/^org/i), li: col(/^li posts$/i), liEr: col(/^li er/i), liF: col(/^li flw$/i),
    x: col(/^x posts$/i), xEr: col(/^x er/i), xF: col(/^x flw$/i),
    ig: col(/^ig posts$/i), igEr: col(/^ig er/i), igF: col(/^ig flw$/i),
    yt: col(/^yt$/i), ytEr: col(/^yt er/i), ytS: col(/^yt subs$/i), total: col(/^total$/i), sov: col(/^sov/i),
  };
  for (const r of st.rows) {
    if (r.length < 10) continue;
    const g = (k) => (C[k] >= 0 && r[C[k]] ? cellVal(r[C[k]].html) : { v: null, marker: "none", raw: "" });
    social[r[C.org].text] = {
      li: g("li"), liEr: g("liEr"), liF: g("liF"), x: g("x"), xEr: g("xEr"), xF: g("xF"),
      ig: g("ig"), igEr: g("igEr"), igF: g("igF"), yt: g("yt"), ytEr: g("ytEr"), ytS: g("ytS"),
      total: g("total").v || 0, sov: g("sov").v || 0,
    };
  }
  // per-org breakdown: presence score + post links
  const posts = {};
  for (const blk of soc.split("</details>")) {
    const d = blk.lastIndexOf("<details");
    if (d < 0) continue;
    const b = blk.slice(d);
    const sm = b.match(/#(\d+)<\/span>\s*<span[^>]*>([\s\S]*?)<\/span>\s*<span[^>]*>(\d+)\/10<\/span>/);
    if (!sm) continue;
    const org = text(sm[2]);
    const groups = [];
    let cur = null;
    const tok = /(<div style="font-size:14px;color:var\(--muted2\);text-transform:uppercase[^"]*">[\s\S]*?<\/div>)|(<div style="font-size:16px;color:var\(--muted2\);line-height:1\.4">([\s\S]*?)<\/div>\s*<div style="font-family:monospace;font-size:14px;color:var\(--muted\);margin-top:3px">([\s\S]*?)<\/div>([\s\S]*?)<\/div>(?=<div style="padding:6px 10px|\s*<\/div>|\s*<div style="margin-top:8px">|$))/g;
    let m;
    while ((m = tok.exec(b))) {
      if (m[1]) { cur = { header: text(m[1]), posts: [] }; groups.push(cur); }
      else if (m[2] && cur) {
        const lm = m[3].match(/<a href="([^"]+)"[^>]*>\[link\]<\/a>/);
        cur.posts.push({
          url: lm ? decode(lm[1]) : null,
          metrics: text(m[4]),
          keywords: [...m[5].matchAll(/<span style="display:inline-block[^"]*">([\s\S]*?)<\/span>/g)].map((k) => text(k[1])),
        });
      }
    }
    posts[org] = { presence: parseInt(sm[3], 10), groups };
  }

  // ── scorecard ──
  const sc = {};
  const scT = tablesOf(sectionOf(html, "score")).find((t) => hIdx(t.headers, /overall/i) >= 0);
  if (!scT) throw new Error("Base report: scorecard table not found");
  const so = hIdx(scT.headers, /^org/i);
  const spct = (cell) => {
    const m = cell.html.match(/<span[^>]*>\s*([\d.]+)%\s*<\/span>/);
    return m ? parseFloat(m[1]) : null;
  };
  const scRows = scT.rows.filter((r) => r.length >= 6 && r[so].text);
  const iPress = hIdx(scT.headers, /press sov/i);
  const iLlm = hIdx(scT.headers, /llm sov/i);
  const iSoc = hIdx(scT.headers, /social sov/i);
  const iOv = hIdx(scT.headers, /overall/i);
  // Older reports (before share-of-voice scoring) print the same three inputs as
  // plain numbers — press score, AI score, presence /10 — and an overall in
  // points, with no % anywhere in the table.
  const legacyScores = scRows.length > 0 && scRows.every((r) => spct(r[iPress]) === null && spct(r[iOv]) === null);
  if (legacyScores) {
    const num = (cell) => parseFloat(cell.text.replace(/[^\d.]/g, "")) || 0;
    const raw = scRows.map((r) => {
      const pm = r[iSoc].text.match(/(\d+)\s*\/\s*10/);
      return { org: r[so].text, press: num(r[iPress]), llm: num(r[iLlm]), presence: pm ? parseInt(pm[1], 10) : 0 };
    });
    const tot = (k) => raw.reduce((s, x) => s + x[k], 0) || 1;
    const [tp, tl, ts] = [tot("press"), tot("llm"), tot("presence")];
    const r1 = (v) => Math.round(v * 10) / 10;
    for (const x of raw) {
      // The current method: each score as a share of all organisations' scores,
      // overall = mean of the three shares (reproduces the printed figures of
      // current-format reports to the decimal).
      const p = (x.press / tp) * 100, l = (x.llm / tl) * 100, s = (x.presence / ts) * 100;
      sc[x.org] = { press: r1(p), llm: r1(l), social: r1(s), overall: r1((p + l + s) / 3), presence: x.presence };
    }
    meta.legacyScores = true;
  } else {
    for (const r of scRows) {
      const presence = r[iSoc].text.match(/(\d+)\/10/);
      sc[r[so].text] = {
        press: spct(r[iPress]) || 0,
        llm: spct(r[iLlm]) || 0,
        social: spct(r[iSoc]) || 0,
        overall: spct(r[iOv]) || 0,
        presence: presence ? parseInt(presence[1], 10) : null,
      };
    }
  }

  return { meta, orgs, printOutlets, tvChannels, press, tv, weeks: weeks.map((w) => w.label), momentum, fieldWeekly, topics: topics.map((t) => t.name), topicCounts, citations, llm, assistants, questions, questionCells, nAns, social, posts, sc };
}

// ─────────────────────────────── statistics ─────────────────────────────────
const mean = (a) => (a.length ? a.reduce((x, y) => x + y, 0) / a.length : 0);
function stat(orgVal, peerVals, allVals) {
  return { v: orgVal, mean: mean(peerVals), min: Math.min(...allVals), max: Math.max(...allVals), n: allVals.length };
}
function rankOf(v, all) {
  const greater = all.filter((x) => x > v + 1e-9).length;
  const ties = all.filter((x) => Math.abs(x - v) <= 1e-9).length;
  return { rank: greater + 1, ties, of: all.length };
}
function rankText(r) { return r.ties <= 2 ? `${r.rank} of ${r.of}` : "—"; }
function dotPos(s) {
  const { v, mean: m, min, max } = s;
  if (v < m - 1e-9) return m > min ? 6 + ((v - min) / (m - min)) * 44 : 50;
  if (v > m + 1e-9) return max > m ? 50 + ((v - m) / (max - m)) * 44 : 50;
  return 50;
}
const dotClass = (pos) => (pos < 37 ? "r" : pos < 63 ? "a" : "g");
const valClass = (v, m) => (v > m + 1e-9 ? "g-good" : v < m - 1e-9 ? "g-bad" : "g-warn");
const stClass = (pos) => (pos < 37 ? "st-r" : pos < 63 ? "st-a" : "st-g");
function fixed(x, d) { return Number(x.toFixed(d)).toString(); }
function pct(x) { return `${Number(x.toFixed(1))}%`; }
function kfmt(x) {
  if (x >= 1e6) return `${Number((x / 1e6).toFixed(1))}M`;
  if (x >= 1000) return `${Number((x / 1000).toFixed(1))}K`;
  return String(Math.round(x));
}

// ─────────────────────────────── dashboard model ────────────────────────────
function buildModel(base, org, opts = {}) {
  if (!base.orgs.includes(org)) {
    const want = org.toLowerCase();
    const hit = base.orgs.find((o) => o.toLowerCase() === want);
    if (!hit) throw new Error(`Org "${org}" not found in the base report. Available: ${base.orgs.join("; ")}`);
    org = hit;
  }
  const A = base.orgs;
  const peers = A.filter((o) => o !== org);
  const N = A.length;
  const M = {};
  M.org = org;
  M.display = opts.displayName || (opts.profile && opts.profile.displayName) || org;
  M.N = N;
  M.P = peers.length;
  M.meta = base.meta;

  const pressArticles = (o) => (base.press[o] ? base.press[o].total : 0) + (base.tv[o] ? base.tv[o].total : 0);
  const tvTotal = (o) => (base.tv[o] ? base.tv[o].total : 0);
  const held = (o) => Object.values(base.topicCounts[o] || {}).filter((n) => n >= 2).length;
  const touched = (o) => Object.values(base.topicCounts[o] || {}).filter((n) => n === 1).length;
  const assistantsNaming = (o) => (base.llm[o] ? Object.values(base.llm[o].per).filter((n) => n > 0).length : 0);
  const soc = (o) => base.social[o] || {};
  const socTotal = (o) => soc(o).total || 0;
  const overall = (o) => (base.sc[o] ? base.sc[o].overall : 0);
  const aeoScore = (o) => Math.round(((base.llm[o] ? base.llm[o].total : 0) / (base.nAns || 45)) * 100);
  const cls = (o) => base.citations[o] || [];
  const dataPct = (o) => (cls(o).length ? (cls(o).filter((a) => /data cited/i.test(a.classification)).length / cls(o).length) * 100 : 0);
  const authPct = (o) => (cls(o).length ? (cls(o).filter((a) => /authorit/i.test(a.classification)).length / cls(o).length) * 100 : 0);
  const zeroCount = (f) => A.filter((o) => f(o) === 0).length;

  M.stats = {
    press: stat(pressArticles(org), peers.map(pressArticles), A.map(pressArticles)),
    tv: stat(tvTotal(org), peers.map(tvTotal), A.map(tvTotal)),
    topics: stat(held(org), peers.map(held), A.map(held)),
    ai: stat(assistantsNaming(org), peers.map(assistantsNaming), A.map(assistantsNaming)),
    social: stat(socTotal(org), peers.map(socTotal), A.map(socTotal)),
    overall: stat(overall(org), peers.map(overall), A.map(overall)),
  };
  M.ranks = {
    press: rankOf(pressArticles(org), A.map(pressArticles)),
    tv: rankOf(tvTotal(org), A.map(tvTotal)),
    topics: rankOf(held(org), A.map(held)),
    ai: rankOf(assistantsNaming(org), A.map(assistantsNaming)),
    social: rankOf(socTotal(org), A.map(socTotal)),
    overall: rankOf(overall(org), A.map(overall)),
  };
  M.nTopics = base.topics.length;
  M.nAssistants = base.assistants.length || 3;
  M.nQuestions = base.questions.length;
  M.zero = { press: zeroCount(pressArticles), ai: zeroCount(assistantsNaming) };

  // press detail
  M.print = {
    org: pressArticles(org) - tvTotal(org),
    orgByOutlet: (base.press[org] || { byOutlet: {} }).byOutlet,
    fieldByOutlet: Object.fromEntries(base.printOutlets.map((h) => [h, peers.reduce((s, p) => s + ((base.press[p] || { byOutlet: {} }).byOutlet[h] || 0), 0)])),
    fieldTv: peers.reduce((s, p) => s + tvTotal(p), 0),
    orgTv: tvTotal(org),
  };
  M.orgArticles = cls(org);

  // momentum
  M.weeks = base.weeks;
  M.orgWeekly = (base.momentum[org] || { vals: base.weeks.map(() => 0) }).vals;
  M.fieldWeekly = base.fieldWeekly ? base.fieldWeekly.vals : base.weeks.map((_, i) => peers.reduce((s, p) => s + ((base.momentum[p] || { vals: [] }).vals[i] || 0), 0));
  M.peakWeek = M.fieldWeekly.reduce((b, v, i) => (v > b.v ? { v, i } : b), { v: -1, i: 0 });

  // topics
  M.heldTopicsByPeers = [...new Set(peers.flatMap((p) => Object.entries(base.topicCounts[p] || {}).filter(([, n]) => n >= 2).map(([k]) => k)))];
  M.peersHolding = peers.filter((p) => held(p) > 0).length;
  M.anyLeader = A.some((o) => Object.values(base.topicCounts[o] || {}).some((n) => n >= 5));
  M.orgTopics = Object.entries(base.topicCounts[org] || {}).filter(([, n]) => n > 0).map(([name, n]) => ({ name, n }));
  M.topicNames = base.topics;

  // citations & authority
  M.cit = {
    articles: stat(cls(org).length, peers.map((p) => cls(p).length), A.map((p) => cls(p).length)),
    aeo: stat(aeoScore(org), peers.map(aeoScore), A.map(aeoScore)),
    auth: stat(authPct(org), peers.map(authPct), A.map(authPct)),
    data: stat(dataPct(org), peers.map(dataPct), A.map(dataPct)),
  };

  // AI
  M.ai = {
    named: base.llm[org] ? base.llm[org].total : 0,
    assistants: assistantsNaming(org),
    fieldTotal: A.reduce((s, o) => s + (base.llm[o] ? base.llm[o].total : 0), 0),
    fieldMeanAnswers: mean(peers.map((p) => (base.llm[p] ? base.llm[p].total : 0))),
    fieldMeanAssistants: mean(peers.map(assistantsNaming)),
    zeroOrgs: zeroCount(assistantsNaming),
    allThree: A.filter((o) => assistantsNaming(o) === (base.assistants.length || 3)).length,
    rows: base.questions.map((q, i) => {
      const c = (base.questionCells[org] || [])[i] || { named: 0, of: M.nAssistants };
      return { n: q.n, text: q.text, named: c.named, of: c.of };
    }),
  };
  M.ai.cohortQuestionsNamed = base.questions.filter((q, i) => A.some((o) => ((base.questionCells[o] || [])[i] || { named: 0 }).named > 0)).length;
  M.ai.orgQuestionsNamed = M.ai.rows.filter((r) => r.named > 0).length;

  // social
  const s0 = soc(org);
  const numPeers = (k) => peers.map((p) => soc(p)[k]).filter((c) => c && c.v !== null && c.marker === null).map((c) => c.v);
  const numPeersPos = (k, erK) => peers.filter((p) => soc(p)[k] && soc(p)[k].v > 0 && soc(p)[erK] && soc(p)[erK].v !== null).map((p) => soc(p)[erK].v);
  M.soc = {
    org: s0,
    presence: (base.posts[org] || {}).presence !== undefined ? base.posts[org].presence : (base.sc[org] || {}).presence,
    presenceMean: mean(peers.map((p) => (base.sc[p] || {}).presence).filter((v) => v !== null && v !== undefined)),
    liMean: mean(numPeers("li")), xMean: mean(numPeers("x")), igMean: mean(numPeers("ig")), ytMean: mean(numPeers("yt")),
    liErMean: mean(numPeersPos("li", "liEr")),
    liMax: Math.max(0, ...numPeers("li")), xMax: Math.max(0, ...numPeers("x")), igMax: Math.max(0, ...numPeers("ig")), ytMax: Math.max(0, ...numPeers("yt")),
    liErMax: Math.max(0, ...numPeersPos("li", "liEr")),
    liErN: numPeersPos("li", "liEr").length,
    ytFieldTotal: A.reduce((s, o) => s + (soc(o).yt && soc(o).yt.v ? soc(o).yt.v : 0), 0),
    share: soc(org).sov,
  };
  const igPosting = A.filter((o) => soc(o).ig && soc(o).ig.v > 0 && soc(o).igF && soc(o).igF.v !== null);
  M.soc.igPosting = igPosting.length;
  M.soc.igFollowMean = mean(igPosting.filter((o) => o !== org).map((o) => soc(o).igF.v));
  M.soc.igRank = s0.ig && s0.ig.v > 0 && s0.igF && s0.igF.v !== null ? igPosting.filter((o) => soc(o).igF.v > s0.igF.v).length + 1 : null;
  const liBig = A.filter((o) => soc(o).liF && soc(o).liF.v > 5000 && soc(o).liEr && soc(o).liEr.v !== null && soc(o).li && soc(o).li.v > 0);
  M.soc.liBigN = liBig.length;
  M.soc.liBigRank = liBig.includes(org) ? liBig.filter((o) => soc(o).liEr.v > s0.liEr.v).length + 1 : null;
  M.postGroups = (base.posts[org] || { groups: [] }).groups;

  // scorecard components
  const scv = (o, k) => (base.sc[o] ? base.sc[o][k] : 0);
  M.sov = {
    press: stat(scv(org, "press"), peers.map((p) => scv(p, "press")), A.map((p) => scv(p, "press"))),
    llm: stat(scv(org, "llm"), peers.map((p) => scv(p, "llm")), A.map((p) => scv(p, "llm"))),
    social: stat(scv(org, "social"), peers.map((p) => scv(p, "social")), A.map((p) => scv(p, "social"))),
    overall: M.stats.overall,
  };
  M.socialShareIsMax = scv(org, "social") >= Math.max(...A.map((p) => scv(p, "social"))) - 1e-9;
  M.profile = opts.profile || {};
  M.sample = !!opts.sample;
  M.sourceName = org;
  return M;
}

