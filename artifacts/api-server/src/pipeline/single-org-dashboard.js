/**
 * Single-org benchmark dashboard ("Triple Media Pulse") — generated from a base report.
 *
 * Takes the full multi-org AQ Intelligence report (the HTML the pipeline writes)
 * and renders ONE organisation's dashboard: that org named, every other org
 * aggregated as a field average + low–high range, never named.
 *
 * Deterministic and offline. No API calls, no fetches, no LLM — it only reads
 * numbers the base report already contains, so generating a dashboard costs
 * nothing beyond a few milliseconds of CPU.
 *
 * Standing rules baked in (see the Raahgiri sample this reproduces):
 *   - the subject org is the only org named; peers appear as mean / low–high / rank
 *   - field average is the arithmetic mean of the OTHER orgs
 *   - figures and plain descriptors only — no evaluative adjectives; colour carries position
 *   - nothing is inferred: content that is not in the base report is only emitted when a
 *     per-org profile supplies it, and is then labelled INFERENCE
 *   - post text and LLM answers are never reproduced (they name other orgs)
 *
 * CLI:
 *   node single-org-dashboard.js --base report.html --org "RaahGiri" [--name "Raahgiri Foundation"]
 *        [--profile profile.json] [--out dashboard.html] [--sample] [--dump-data data.json]
 *   node single-org-dashboard.js --base report.html --all --out-dir ./dashboards
 *   node single-org-dashboard.js --base report.html --list
 */
