const andList = (a) => (a.length <= 1 ? a.join("") : `${a.slice(0, -1).join(", ")} and ${a[a.length - 1]}`);
const fx = (x, d) => x.toFixed(d);
const STOP = new Set(["for", "and", "of", "the", "on", "in"]);
function shortName(display, profile) {
  if (profile && profile.shortName) return profile.shortName;
  const w = display.split(/[\s,]+/).filter(Boolean);
  if (w.length <= 2) return display;
  return w.filter((x) => !STOP.has(x.toLowerCase())).map((x) => x[0].toUpperCase()).join("");
}

function fmtStat(s, dec, isPct) {
  const f = (x) => (isPct ? pct(x) : fixed(x, dec));
  return { v: f(s.v), mean: f(s.mean), min: f(s.min), max: f(s.max) };
}

/** One-line description of a platform cell (posts + engagement + followers). */
function platformCell(c, erCell, fCell, noun) {
  if (!c) return "no data";
  if (c.marker === "nohandle") return "no handle configured";
  if (c.marker === "failed") return "data unavailable";
  const bits = [`${c.v || 0} ${noun}`];
  if (c.v > 0 && erCell && erCell.v !== null) bits.push(erCell.raw);
  if (fCell && fCell.v !== null) bits.push(kfmt(fCell.v));
  return bits.join(" · ");
}

function hintGlyphs(header) {
  // "LinkedIn — 8 AQ posts · 9.7K followers · ER 0.604% · ♥ 409 · 💬 10 · ↗ 49"  ->  plain words
  const parts = header.replace(/\s+/g, " ").split(/\s+·\s+/).map((p) => p.trim());
  return parts
    .map((p, i) => {
      if (i === 0) return p.replace(/^.*? — /, "");
      return p
        .replace(/^ER (.*)$/, "engagement rate $1")
        .replace(/^♥ (\S+)$/, "$1 likes")
        .replace(/^💬 (\S+)$/, "$1 comments")
        .replace(/^↗ (\S+)$/, "$1 shares")
        .replace(/^↩ (\S+)$/, "$1 replies")
        .replace(/^↻ (\S+)$/, "$1 reposts")
        .replace(/^👁 (\S+)$/, "$1 views");
    })
    .map(esc)
    .join(" &middot; ");
}
function postMeta(metrics) {
  const dm = metrics.match(/\d{4}-\d{2}-\d{2}/);
  const bits = metrics.replace(/\d{4}-\d{2}-\d{2}/, "").split("·").map((b) => b.trim()).filter(Boolean).map((b) =>
    b.replace(/^♥ (\S+)$/, "$1 likes").replace(/^💬 (\S+)$/, "$1 comments").replace(/^↗ (\S+)$/, "$1 shares")
      .replace(/^↩ (\S+)$/, "$1 replies").replace(/^↻ (\S+)$/, "$1 reposts").replace(/^👁 (\S+)$/, "$1 views"));
  return [dm ? dm[0] : "", ...bits].filter(Boolean).map(esc).join(" &middot; ");
}

