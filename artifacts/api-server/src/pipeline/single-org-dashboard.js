// Snapshot = the benchmark dashboard cut down to its first scorecard section
// (Section 00): same header, same bars and table, nothing after it.
function toSnapshot(html) {
  const from = html.indexOf("<!-- ================= 01 =");
  const to = html.indexOf('<footer class="rf">');
  if (from < 0 || to < 0) throw new Error("toSnapshot: dashboard markers not found");
  return (html.slice(0, from) + html.slice(to))
    .replace(/<div class="nav-lbl">(?!Overview)[^<]*<\/div>\s*/g, "")
    .replace(/<a class="nav-a" href="#(?!scorecard")[^"]*">[^<]*<\/a>\s*/g, "");
}

// Give an already-generated one-org dashboard (benchmark / snapshot) the light/dark
// toggle and the INFERENCE-note styling. Purely additive and idempotent: figures
// and wording are untouched, so it works on files whose source report is gone.
function addTheme(html) {
  if (/id="theme-btn"/.test(html)) return html;
  if (!/name="emerald-report-type"/.test(html)) throw new Error("addTheme: not a one-organisation dashboard");
  const styleEnd = html.indexOf("</style>");
  const bodyOpen = html.search(/<body[^>]*>/);
  const scriptEnd = html.lastIndexOf("</script>");
  if (styleEnd < 0 || bodyOpen < 0 || scriptEnd < 0) throw new Error("addTheme: unexpected page structure");
  const bodyTagEnd = html.indexOf(">", bodyOpen) + 1;
  return (
    html.slice(0, styleEnd) + THEME_CSS + "\n</style>\n<script>" + THEME_HEAD_JS + "</script>" +
    html.slice(styleEnd + "</style>".length, bodyTagEnd) + "\n" + THEME_BUTTON +
    html.slice(bodyTagEnd, scriptEnd) + THEME_JS + html.slice(scriptEnd)
  );
}

function buildSingleOrgDashboard(baseHtml, opts = {}) {
  const view = opts.view === "snapshot" ? "snapshot" : "benchmark";
  const base = opts.base || parseBaseReport(baseHtml);
  const M = buildModel(base, opts.org, opts);
  M.tvChannels = base.tvChannels;
  M.tvChannelsN = base.tvChannels.length;
  M.assistants = base.assistants;
  M.view = view;
  const html = renderDashboard(M);
  return view === "snapshot" ? toSnapshot(html) : html;
}

function slug(s) { return String(s).toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, ""); }

// ─────────────────────────────── CLI ────────────────────────────────────────
function main(argv) {
  const a = {};
  for (let i = 0; i < argv.length; i++) {
    const k = argv[i];
    if (k.startsWith("--")) {
      const key = k.slice(2);
      const nxt = argv[i + 1];
      if (nxt === undefined || nxt.startsWith("--")) a[key] = true;
      else { a[key] = nxt; i++; }
    }
  }
  if (a["add-theme"]) {
    const src = a["add-theme"];
    const out = a.out || src;
    fs.writeFileSync(out, addTheme(fs.readFileSync(src, "utf8")));
    console.log("wrote", out);
    return;
  }
  if (!a.base) {
    console.error("Usage: node single-org-dashboard.js --base report.html (--org \"Name\" [--name \"Display\"] [--profile p.json] [--out f.html] [--view benchmark|snapshot] [--sample] | --all --out-dir dir | --list | --add-theme dashboard.html [--out f.html])");
    process.exit(2);
  }
  const html = fs.readFileSync(a.base, "utf8");
  const base = parseBaseReport(html);
  if (a.list) { console.log(base.orgs.join("\n")); return; }
  const profile = a.profile ? JSON.parse(fs.readFileSync(a.profile, "utf8")) : undefined;
  if (a.all) {
    const dir = a["out-dir"] || ".";
    fs.mkdirSync(dir, { recursive: true });
    for (const org of base.orgs) {
      const out = path.join(dir, `${slug(org)}-dashboard.html`);
      fs.writeFileSync(out, buildSingleOrgDashboard(html, { base, org, sample: !!a.sample, view: a.view }));
      console.log("wrote", out);
    }
    return;
  }
  if (!a.org) { console.error("--org is required (use --list to see names)"); process.exit(2); }
  const out = a.out || `${slug(a.org)}-dashboard.html`;
  fs.writeFileSync(out, buildSingleOrgDashboard(html, { base, org: a.org, displayName: a.name, profile, sample: !!a.sample, view: a.view }));
  if (a["dump-data"]) fs.writeFileSync(a["dump-data"], JSON.stringify(base, null, 2));
  console.log("wrote", out);
}

module.exports.buildSingleOrgDashboard = buildSingleOrgDashboard;
module.exports.listOrgs = (html) => parseBaseReport(html).orgs;
module.exports.addTheme = addTheme;
